#include <iostream>   // console output (std::cout)
#include <fstream>    // reading puzzle files (std::ifstream)
#include <string>     // std::string for file names
#include <vector>     // std::vector to store the solutions
#include <array>      // std::array for the fixed 9x9 grid

// ---------------------------------------------------------------------------
// Class Puzzle: owns a 9x9 grid and knows how to load and print itself.
// ---------------------------------------------------------------------------
class Puzzle {
public:
    static const int SIZE = 9;                 // grid is SIZE x SIZE (9 x 9)

    Puzzle() {                                 // default constructor
        for (auto& row : cells) row.fill(0);   // start with every cell empty (0 = blank)
    }

    // Reads a puzzle from a file; returns false if the file is missing or malformed.
    bool loadFromFile(const std::string& fileName) {
        std::ifstream in(fileName);            // open the file for reading
        if (!in) return false;                 // could not open -> report failure
        int count = 0;                         // how many cells we have read so far
        char ch;                               // one character at a time
        while (count < SIZE * SIZE && in.get(ch)) {  // stop after 81 cells or end of file
            if (ch >= '1' && ch <= '9') {              // a given digit
                cells[count / SIZE][count % SIZE] = ch - '0';  // convert char to int, store it
                count++;                               // move to next cell
            } else if (ch == '_' || ch == '0' || ch == '.') {  // a blank square
                cells[count / SIZE][count % SIZE] = 0;         // store 0 for blank
                count++;                                       // move to next cell
            }                                          // anything else (spaces, newlines) is skipped
        }
        return count == SIZE * SIZE;           // success only if we got all 81 cells
    }

    int get(int r, int c) const { return cells[r][c]; }     // read one cell
    void set(int r, int c, int v) { cells[r][c] = v; }      // write one cell

    // Prints the grid, one row per line, '_' for blanks, with gaps between 3x3 blocks.
    void print(std::ostream& out) const {
        for (int r = 0; r < SIZE; r++) {                    // go through each row
            if (r > 0 && r % 3 == 0) out << "------+-------+------\n";  // horizontal block divider
            for (int c = 0; c < SIZE; c++) {                // go through each column
                if (c > 0 && c % 3 == 0) out << "| ";       // vertical block divider
                if (cells[r][c] == 0) out << "_";           // blank cell
                else out << cells[r][c];                    // filled cell
                out << " ";                                 // space between cells
            }
            out << "\n";                                    // end of row
        }
    }

private:
    std::array<std::array<int, SIZE>, SIZE> cells;          // the grid itself
};

// ---------------------------------------------------------------------------
// Class Solver: finds ALL solutions of a Puzzle using recursive backtracking.
// Bitmasks track which digits are already used in each row, column, and block,
// so checking a candidate is a couple of bit operations instead of a grid scan.
// ---------------------------------------------------------------------------
class Solver {
public:
    explicit Solver(const Puzzle& start) : board(start) {   // copy the puzzle to work on
        for (int i = 0; i < 9; i++) rowUsed[i] = colUsed[i] = boxUsed[i] = 0;  // nothing used yet
    }

    // Public entry point: sets up the masks, runs the search, returns solution count.
    int solve() {
        solutions.clear();                          // forget any earlier results
        if (!initMasks()) return 0;                 // givens already break the rules -> no solution
        search(countGivens());                      // start recursion with the givens already filled
        return (int)solutions.size();               // how many solutions were found
    }

    const std::vector<Puzzle>& getSolutions() const { return solutions; }  // access results

private:
    Puzzle board;                                   // working copy of the puzzle
    int rowUsed[9], colUsed[9], boxUsed[9];         // bit d-1 set => digit d is used in that unit
    std::vector<Puzzle> solutions;                  // every complete solution discovered

    static int boxIndex(int r, int c) { return (r / 3) * 3 + (c / 3); }  // which 3x3 block a cell is in

    int countGivens() const {                       // count the cells that start out filled
        int n = 0;
        for (int r = 0; r < 9; r++)
            for (int c = 0; c < 9; c++)
                if (board.get(r, c) != 0) n++;
        return n;
    }

    // Fills the masks from the given digits; returns false if a given digit repeats in a unit.
    bool initMasks() {
        for (int r = 0; r < 9; r++) {
            for (int c = 0; c < 9; c++) {
                int d = board.get(r, c);            // digit in this cell (0 if blank)
                if (d == 0) continue;               // blanks add nothing
                int bit = 1 << (d - 1);             // mask bit for this digit
                int b = boxIndex(r, c);             // block of this cell
                if ((rowUsed[r] & bit) || (colUsed[c] & bit) || (boxUsed[b] & bit))
                    return false;                   // duplicate found -> puzzle is invalid
                rowUsed[r] |= bit;                  // mark digit used in row
                colUsed[c] |= bit;                  // mark digit used in column
                boxUsed[b] |= bit;                  // mark digit used in block
            }
        }
        return true;                                // all givens are consistent
    }

    // Recursive depth-first search. 'filled' = number of cells filled so far.
    void search(int filled) {
        if (filled == 81) {                         // base case: every cell is filled
            solutions.push_back(board);             // save a copy of this solution
            return;                                 // go back to look for more
        }

        // Pick the empty cell with the FEWEST candidates (fail-first heuristic).
        int bestR = -1, bestC = -1, bestMask = 0, bestCount = 10;
        for (int r = 0; r < 9; r++) {
            for (int c = 0; c < 9; c++) {
                if (board.get(r, c) != 0) continue;                 // skip filled cells
                int mask = ~(rowUsed[r] | colUsed[c] | boxUsed[boxIndex(r, c)]) & 0x1FF;  // allowed digits
                int cnt = __builtin_popcount(mask);                 // how many digits are allowed
                if (cnt < bestCount) {                              // better (more constrained) cell?
                    bestCount = cnt; bestMask = mask;               // remember its candidate info
                    bestR = r; bestC = c;                           // remember its position
                }
            }
        }
        if (bestCount == 0) return;                 // dead end: an empty cell has no candidates, backtrack

        int b = boxIndex(bestR, bestC);             // block of the chosen cell
        for (int d = 1; d <= 9; d++) {              // try each digit 1..9
            int bit = 1 << (d - 1);                 // mask bit for this digit
            if (!(bestMask & bit)) continue;        // skip digits that are not candidates
            board.set(bestR, bestC, d);             // place the digit
            rowUsed[bestR] |= bit; colUsed[bestC] |= bit; boxUsed[b] |= bit;  // mark it used
            search(filled + 1);                     // recurse with one more cell filled
            board.set(bestR, bestC, 0);             // undo the placement (backtrack)
            rowUsed[bestR] &= ~bit; colUsed[bestC] &= ~bit; boxUsed[b] &= ~bit;  // unmark it
        }
    }
};

// ---------------------------------------------------------------------------
// Class PuzzleRunner: loads one file, runs the solver, and reports the results.
// ---------------------------------------------------------------------------
class PuzzleRunner {
public:
    explicit PuzzleRunner(const std::string& file) : fileName(file) {}  // remember the file name

    void run() const {
        std::cout << "==============================\n";
        std::cout << fileName << "\n";                       // print the puzzle file name
        Puzzle puzzle;                                       // empty puzzle to fill from file
        if (!puzzle.loadFromFile(fileName)) {                // try to read the file
            std::cout << "Could not read a valid puzzle from this file.\n\n";
            return;                                          // nothing more we can do
        }
        std::cout << "Puzzle:\n";
        puzzle.print(std::cout);                             // show the starting puzzle

        Solver solver(puzzle);                               // build a solver for this puzzle
        int count = solver.solve();                          // run the recursive search
        if (count == 0) {                                    // nothing found
            std::cout << "\nNo solution found\n\n";
            return;
        }
        std::cout << "\nSolutions found: " << count << "\n"; // report how many
        int n = 1;                                           // solution counter for labels
        for (const Puzzle& s : solver.getSolutions()) {      // print every solution
            std::cout << "\nSolution " << n++ << ":\n";
            s.print(std::cout);
        }
        std::cout << "\n";
    }

private:
    std::string fileName;                                    // name of the puzzle file to process
};

int main() {
    for (int i = 1; i <= 5; i++) {                           // puzzle1.txt through puzzle5.txt
        PuzzleRunner runner("puzzle" + std::to_string(i) + ".txt");  // build a runner for this file
        runner.run();                                        // load, solve, print
    }
    return 0;                                                // normal exit
}
